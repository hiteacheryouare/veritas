/// The currency with this code, ignoring case. The empty code is "None".
pub fn currency(code: &str) -> Option<&'static Currency> {
	CURRENCIES
		.iter()
		.find(|currency| currency.code.eq_ignore_ascii_case(code))
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn the_table_matches_actuals_list() {
		assert_eq!(CURRENCIES.len(), 55);
		assert_eq!(CURRENCIES[0].name, "None");
		let usd = currency("usd").unwrap();
		assert_eq!((usd.symbol, usd.decimal_places), ("$", 2));
		assert_eq!(
			currency("INR").unwrap().number_format,
			NumberStyle::CommaDotIn
		);
		assert!(currency("XXX").is_none());
	}
}
